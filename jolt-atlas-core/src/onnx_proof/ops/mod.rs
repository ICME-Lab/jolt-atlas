/// Dispatches on every `Op` variant, binding the inner value to `$inner`
/// and evaluating `$body`. The match is exhaustive on purpose: adding a
/// variant to `atlas_trace::Op` must fail to compile here until the proof
/// layer handles it.
macro_rules! dispatch_operator {
    ($node:expr, |$inner:ident| $body:expr) => {
        match &$node.operator {
            Op::And($inner) => $body,
            Op::Add($inner) => $body,
            Op::Broadcast($inner) => $body,
            Op::Constant($inner) => $body,
            Op::Cos($inner) => $body,
            Op::Cube($inner) => $body,
            Op::Clamp($inner) => $body,
            Op::Concat($inner) => $body,
            Op::Div($inner) => $body,
            Op::Erf($inner) => $body,
            Op::Einsum($inner) => $body,
            Op::GatherSmall($inner) => $body,
            Op::GatherLarge($inner) => $body,
            Op::Identity($inner) => $body,
            Op::Iff($inner) => $body,
            Op::Input($inner) => $body,
            Op::IsNan($inner) => $body,
            Op::MeanOfSquares($inner) => $body,
            Op::MoveAxis($inner) => $body,
            Op::Mul($inner) => $body,
            Op::Neg($inner) => $body,
            Op::ReLU($inner) => $body,
            Op::Reshape($inner) => $body,
            Op::Rsqrt($inner) => $body,
            Op::ScalarConstDiv($inner) => $body,
            Op::Sigmoid($inner) => $body,
            Op::Sin($inner) => $body,
            Op::Slice($inner) => $body,
            Op::SoftmaxLastAxis($inner) => $body,
            Op::Square($inner) => $body,
            Op::Sub($inner) => $body,
            Op::Sum($inner) => $body,
            Op::Tanh($inner) => $body,
        }
    };
}

/// Prover dispatcher for operator proofs.
///
/// This struct provides a single entry point for generating proofs for any computation node,
/// dispatching to the appropriate operator-specific proving logic.
pub struct OperatorProver;

impl OperatorProver {
    /// Generate a proof for the given computation node.
    ///
    /// Dispatches to the operator-specific proving implementation and returns
    /// one or more sumcheck proofs (most operators return a single proof).
    ///
    /// # Arguments
    ///
    /// * `node` - The computation node to prove
    /// * `prover` - The prover state containing trace, transcript, and accumulator
    ///
    /// # Returns
    ///
    /// A tuple containing the node's evaluation-reduction proof and the
    /// execution proof vector.
    pub fn prove<F, T>(
        node: &ComputationNode,
        prover: &mut Prover<F, T>,
    ) -> (EvalReductionProof<F>, ExecutionProofs<F>)
    where
        F: JoltField,
        T: Transcript,
    {
        dispatch_operator!(node, |inner| Self::prove_and_reduce_node(
            inner, node, prover
        ))
    }

    fn prove_and_reduce_node<F, T, O>(
        operator: &O,
        node: &ComputationNode,
        prover: &mut Prover<F, T>,
    ) -> (EvalReductionProof<F>, ExecutionProofs<F>)
    where
        F: JoltField,
        T: Transcript,
        O: ProveOp<F, T>,
    {
        match operator.reduction_flow() {
            ReductionFlow::Default => {
                let eval_reduction_proof = NodeEvalReduction::prove(prover, node);
                let execution_proofs = operator.prove(node, prover);
                // Store eval reduction proof and execution proofs as needed
                (eval_reduction_proof, execution_proofs)
            }
            ReductionFlow::Custom => operator.prove_with_reduction(node, prover),
        }
    }
}

/// Macro to implement `OpLayout`, `ProveOp` and `VerifyOp` for standard sumcheck-based operators.
///
/// These operators all follow the same pattern:
/// 1. Create params from computation node and accumulator
/// 2. Initialize prover with trace and params
/// 3. Run sumcheck and store proof
#[macro_export]
macro_rules! impl_standard_sumcheck_proof_api {
    ($inner_ty:ty, $params_ty:ident, $prover_ty:ident, $verifier_ty:ident) => {
        $crate::impl_standard_sumcheck_proof_api!(
            @impl $inner_ty,
            |node: &ComputationNode, prover: &mut Prover<F, T>| {
                use $crate::onnx_proof::ops::{$params_ty, $prover_ty};
                let params = $params_ty::new(node.clone(), &prover.accumulator);
                $prover_ty::initialize(&prover.trace, params)
            },
            |node: &ComputationNode,
             _: &atlas_trace::Model,
             accumulator: &atlas_sumcheck::opening_proof::VerifierOpeningAccumulator<F>,
             _: &mut T| {
                use $crate::onnx_proof::ops::$verifier_ty;
                $verifier_ty::new(node.clone(), accumulator)
            }
        );
    };
    ($inner_ty:ty, relation $relation:ty) => {
        $crate::impl_standard_sumcheck_proof_api!(
            @impl $inner_ty,
            |node: &ComputationNode, prover: &mut Prover<F, T>| {
                use $crate::onnx_proof::relation::{RelationParams, RelationProver};
                let params = RelationParams::<F, $relation>::new(
                    <$relation as jolt_claims::SymbolicSumcheck>::new(node.clone()),
                    &prover.accumulator,
                    &mut prover.transcript,
                );
                RelationProver::initialize(&prover.trace, params)
            },
            |node: &ComputationNode,
             _: &atlas_trace::Model,
             accumulator: &atlas_sumcheck::opening_proof::VerifierOpeningAccumulator<F>,
             transcript: &mut T| {
                $crate::onnx_proof::relation::RelationVerifier::<F, $relation>::new(
                    <$relation as jolt_claims::SymbolicSumcheck>::new(node.clone()),
                    accumulator,
                    transcript,
                )
            }
        );
    };
    ($inner_ty:ty, model_relation $relation:ty) => {
        $crate::impl_standard_sumcheck_proof_api!(
            @impl $inner_ty,
            |node: &ComputationNode, prover: &mut Prover<F, T>| {
                use $crate::onnx_proof::relation::{RelationParams, RelationProver};
                let params = RelationParams::<F, $relation>::new(
                    <$relation>::for_node(&prover.preprocessing.model, node.clone()),
                    &prover.accumulator,
                    &mut prover.transcript,
                );
                RelationProver::initialize(&prover.trace, params)
            },
            |node: &ComputationNode,
             model: &atlas_trace::Model,
             accumulator: &atlas_sumcheck::opening_proof::VerifierOpeningAccumulator<F>,
             transcript: &mut T| {
                $crate::onnx_proof::relation::RelationVerifier::<F, $relation>::new(
                    <$relation>::for_node(model, node.clone()),
                    accumulator,
                    transcript,
                )
            }
        );
    };
    (@impl $inner_ty:ty, $make_prover:expr, $make_verifier:expr) => {

        impl<F: JoltField, T: Transcript> $crate::onnx_proof::ops::ProveOp<F, T> for $inner_ty {
            #[tracing::instrument(skip(node, prover))]
            fn prove(
                &self,
                node: &ComputationNode,
                prover: &mut Prover<F, T>,
            ) -> Vec<(ProofId, SumcheckInstanceProof<F>)> {
                use atlas_sumcheck::sumcheck::Sumcheck;

                let mut prover_sumcheck = ($make_prover)(node, &mut *prover);
                let (proof, _) = Sumcheck::prove(
                    &mut prover_sumcheck,
                    &mut prover.accumulator,
                    &mut prover.transcript,
                );
                vec![(ProofId(node.idx, ProofType::Execution), proof)]
            }
        }

    };
}

/// Implement [`ProveOp`]/[`VerifyOp`] for an op proven by a zero-round relation (a tie) built
/// from its node: the prover appends the tie's openings, the verifier checks it.
#[macro_export]
macro_rules! impl_tie_proof_api {
    ($inner_ty:ty, $relation:ty) => {
        impl<F: JoltField, T: Transcript> $crate::onnx_proof::ops::ProveOp<F, T> for $inner_ty {
            #[tracing::instrument(skip(node, prover))]
            fn prove(
                &self,
                node: &ComputationNode,
                prover: &mut Prover<F, T>,
            ) -> Vec<(ProofId, SumcheckInstanceProof<F>)> {
                $crate::onnx_proof::relation::prove_tie(
                    &<$relation as jolt_claims::SymbolicSumcheck>::new(node.clone()),
                    &prover.trace,
                    &mut prover.accumulator,
                    &mut prover.transcript,
                );
                Vec::new()
            }
        }
    };
}

pub use impl_standard_sumcheck_proof_api;

/// Macro to implement [`ProveOp`]/[`VerifyOp`] for element-wise operators that
/// fuse a rescaling division + saturating clamp (`Mul`, `Square`, `Cube`).
///
/// Wraps the operator's own arithmetic sumcheck (`Params`/`Prover`/`Verifier`,
/// emitted under [`ProofType::RescaleArith`]) with the shared
/// [`fused_rebase`](crate::onnx_proof::fused_rebase) stages:
///
/// 1. `prove_pre` — append the remainder advice + discharge the clamp.
/// 2. the operator's arithmetic sumcheck (`acc(r) = rescaled·2^S + R`).
/// 3. `prove_remainder_rc` — range-check the remainder (non-scalar only).
///
/// When the operator is *not* fused (`scale == 0`, a raw building-block product),
/// only step (2) runs and its claim is the plain node-output opening.
#[macro_export]
macro_rules! impl_fused_rescale_proof_api {
    ($inner_ty:ty, $params_ty:ident, $prover_ty:ident, $verifier_ty:ident) => {
        $crate::impl_fused_rescale_proof_api!(
            @impl $inner_ty,
            |node: &ComputationNode, prover: &mut Prover<F, T>| {
                use $crate::onnx_proof::ops::{$params_ty, $prover_ty};
                let params = $params_ty::new(node.clone(), &prover.accumulator);
                $prover_ty::initialize(&prover.trace, params)
            },
            |node: &ComputationNode,
             _: &atlas_trace::Model,
             accumulator: &atlas_sumcheck::opening_proof::VerifierOpeningAccumulator<F>,
             _: &mut T| {
                use $crate::onnx_proof::ops::$verifier_ty;
                $verifier_ty::new(node.clone(), accumulator)
            }
        );
    };
    ($inner_ty:ty, relation $relation:ty) => {
        $crate::impl_fused_rescale_proof_api!(
            @impl $inner_ty,
            |node: &ComputationNode, prover: &mut Prover<F, T>| {
                use $crate::onnx_proof::relation::{RelationParams, RelationProver};
                let params = RelationParams::<F, $relation>::new(
                    <$relation as jolt_claims::SymbolicSumcheck>::new(node.clone()),
                    &prover.accumulator,
                    &mut prover.transcript,
                );
                RelationProver::initialize(&prover.trace, params)
            },
            |node: &ComputationNode,
             _: &atlas_trace::Model,
             accumulator: &atlas_sumcheck::opening_proof::VerifierOpeningAccumulator<F>,
             transcript: &mut T| {
                $crate::onnx_proof::relation::RelationVerifier::<F, $relation>::new(
                    <$relation as jolt_claims::SymbolicSumcheck>::new(node.clone()),
                    accumulator,
                    transcript,
                )
            }
        );
    };
    (@impl $inner_ty:ty, $make_prover:expr, $make_verifier:expr) => {

        impl<F: JoltField, T: Transcript> $crate::onnx_proof::ops::ProveOp<F, T> for $inner_ty {
            #[tracing::instrument(skip(node, prover))]
            fn prove(
                &self,
                node: &ComputationNode,
                prover: &mut Prover<F, T>,
            ) -> Vec<(ProofId, SumcheckInstanceProof<F>)> {
                use atlas_sumcheck::sumcheck::Sumcheck;
                use $crate::onnx_proof::{clamp_lookups::is_scalar, fused_rebase};

                let fused = fused_rebase::fuses_rebase(node);
                let mut proofs = Vec::new();
                let remainder = if fused {
                    let (pre_proofs, remainder) = fused_rebase::prove_pre(node, prover);
                    proofs.extend(pre_proofs);
                    Some(remainder)
                } else {
                    None
                };

                let mut prover_sumcheck = ($make_prover)(node, &mut *prover);
                let (proof, _) = Sumcheck::prove(
                    &mut prover_sumcheck,
                    &mut prover.accumulator,
                    &mut prover.transcript,
                );
                proofs.push((ProofId(node.idx, ProofType::RescaleArith), proof));

                if fused && !is_scalar(node) {
                    proofs.extend(fused_rebase::prove_remainder_rc(
                        node,
                        prover,
                        remainder.as_ref().expect("fused"),
                    ));
                }
                proofs
            }
        }

    };
}

pub use impl_fused_rescale_proof_api;
