//! # atlas-trace
//!
//! Deterministic fixed-point IR, semantics, and trace engine for the
//! jolt-atlas zkML prover. Successor to `atlas-onnx-tracer`'s backend.
//!
//! ## The behavioral contract
//!
//! - Quantized values are `i32` at one global power-of-two scale
//!   ([`id::Scale`]): `q` represents `q / 2^scale`.
//! - Fused-rescale ops (einsum, mul, square, cube, mean-of-squares)
//!   accumulate in `i64`, then split `acc = quotient·D + remainder`
//!   (Euclidean, `remainder ∈ [0, D)`) and emit the quotient, which must lie in
//!   `i32`. The quotient and remainder are captured in the trace for the prover.
//! - Division-like ops capture their advice the same way: `ScalarConstDiv` its
//!   floor-division remainder, `Rsqrt` its division quotient and both
//!   remainders, `Sin` and `Cos` the period reduction their table indexes by
//!   ([`trace::NodeAux`]).
//! - Arithmetic is exact or absent: a sum or difference (each pairwise step of
//!   Add and Sub), an axis sum, a negation or a rescaled quotient outside `i32`
//!   is an execution error, never a clamped value.
//! - Softmax over a row is the output table read at `min(c − x, top)`, with the shift `c`
//!   the smallest integer at or above the row's maximum whose sum-table row sum does not
//!   exceed the sum scale ([`semantics::softmax`]); the shift, the addresses and the two
//!   row gaps are captured for the prover.
//! - Nonlinear ops are lookup tables generated by pure integer arithmetic in
//!   [`semantics`], versioned by [`id::SemVersion`]. The prover materializes
//!   its tables by calling the same functions, so tracer and prover agree
//!   bit for bit by construction — no platform floating point anywhere.
//! - Dimensions are padded per-dimension to powers of two at compile time;
//!   every op declares how it behaves under padding.

