//! # atlas-trace
//!
//! Deterministic fixed-point IR, semantics, and trace engine for the
//! jolt-atlas zkML prover. Successor to `atlas-onnx-tracer`'s backend.
//!
//! ## The behavioral contract
//!
//! - Quantized values are `i32` at one global power-of-two scale
//!   ([`id::Scale`]): `q` represents `q / 2^scale`.
//! - Fused-rescale ops (einsum, mul, square, cube, mean-of-squares)
//!   accumulate in `i64`, then split `acc = quotient·D + remainder`
//!   (Euclidean, `remainder ∈ [0, D)`) and emit
//!   `output = saturating_clamp_i32(quotient)`. The quotient and remainder
//!   are captured in the trace for the prover.
//! - Nonlinear ops are lookup tables generated by pure integer arithmetic in
//!   [`semantics`], versioned by [`id::SemVersion`]. The prover materializes
//!   its tables by calling the same functions, so tracer and prover agree
//!   bit for bit by construction — no platform floating point anywhere.
//! - Dimensions are padded per-dimension to powers of two at compile time;
//!   every op declares how it behaves under padding.

